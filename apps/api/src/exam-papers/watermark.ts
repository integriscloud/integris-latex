import fontkit from '@pdf-lib/fontkit';
import { readFileSync } from 'node:fs';
import { degrees, PDFDocument, rgb } from 'pdf-lib';

// The same TrueType font as the receipts: names keep their accents (é, ɛ, ŋ...).
const FONT = readFileSync(new URL('../../assets/fonts/PlusJakartaSans.ttf', import.meta.url));

/** Number of pages of a PDF (a frozen subject, checked once when it is stored). */
export async function pageCount(pdf: Uint8Array): Promise<number> {
  const document = await PDFDocument.load(pdf, { updateMetadata: false });
  return document.getPageCount();
}

/**
 * The subject with a nominative watermark on every page (docs/spec.md, "Aperçu"): the line
 * diagonally across the page, lightly, and again in the bottom margin. Generated by the server
 * for each opening, from the frozen subject; the clean file is never sent to a preview.
 */
export async function watermark(pdf: Uint8Array, line: string): Promise<Uint8Array> {
  const document = await PDFDocument.load(pdf, { updateMetadata: false });
  document.registerFontkit(fontkit);
  const font = await document.embedFont(FONT, { subset: true });
  const color = rgb(0.7, 0.09, 0.09);
  for (const page of document.getPages()) {
    const { width, height } = page.getSize();
    // Diagonal: sized to the page diagonal, centered.
    const diagonal = Math.hypot(width, height) * 0.8;
    const size = Math.max(
      10,
      Math.min(36, diagonal / Math.max(1, font.widthOfTextAtSize(line, 1))),
    );
    const textWidth = font.widthOfTextAtSize(line, size);
    const angle = Math.atan2(height, width);
    page.drawText(line, {
      x: width / 2 - (Math.cos(angle) * textWidth) / 2 + (Math.sin(angle) * size) / 2,
      y: height / 2 - (Math.sin(angle) * textWidth) / 2 - (Math.cos(angle) * size) / 2,
      size,
      font,
      color,
      opacity: 0.22,
      rotate: degrees((angle * 180) / Math.PI),
    });
    // Footer: readable on paper even when the diagonal is faint.
    const footer = Math.min(9, (width - 40) / Math.max(1, font.widthOfTextAtSize(line, 1)));
    page.drawText(line, {
      x: (width - font.widthOfTextAtSize(line, footer)) / 2,
      y: 14,
      size: footer,
      font,
      color,
      opacity: 0.85,
    });
  }
  document.setProducer('Integris LaTeX');
  return document.save({ useObjectStreams: true });
}
